import React, { useState } from 'react';
import { AlertCircle, CheckCircle2, CheckSquare, Copy, Shield, ShieldCheck } from 'lucide-react';
import { ProtectionRecommendation } from '../../types';

interface RecommendationsCardProps {
  recommendations: ProtectionRecommendation[];
  isThreat: boolean;
}

export const RecommendationsCard: React.FC<RecommendationsCardProps> = ({
  recommendations,
  isThreat,
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopyChecklist = () => {
    const checklistText = recommendations
      .map((r, i) => `[ ] ${i + 1}. [${r.priority}] ${r.action}\n    Rationale: ${r.rationale}`)
      .join('\n\n');
    navigator.clipboard.writeText(
      `--- SCAMSHIELD DEFENSIVE ACTION CHECKLIST ---\n\n${checklistText}\n\nGenerated by ScamShield AI`
    );
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const getPriorityStyle = (priority: string) => {
    switch (priority.toUpperCase()) {
      case 'URGENT':
        return {
          border: 'border-red-500/50 bg-red-950/20',
          badge: 'bg-red-500/20 text-red-400 border-red-500/40',
          Icon: AlertCircle,
          iconColor: 'text-red-400',
        };
      case 'RECOMMENDED':
        return {
          border: 'border-amber-500/50 bg-amber-950/20',
          badge: 'bg-amber-500/20 text-amber-400 border-amber-500/40',
          Icon: Shield,
          iconColor: 'text-amber-400',
        };
      default:
        return {
          border: 'border-blue-500/50 bg-blue-950/20',
          badge: 'bg-blue-500/20 text-blue-400 border-blue-500/40',
          Icon: ShieldCheck,
          iconColor: 'text-blue-400',
        };
    }
  };

  return (
    <div className="bg-slate-900/80 border border-slate-800 rounded-lg p-5 space-y-4 shadow-sm">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-800 pb-3">
        <div className="flex items-center gap-2">
          <CheckSquare className="w-4 h-4 text-emerald-400" />
          <h3 className="font-mono text-sm font-semibold tracking-wide text-white uppercase">
            Protective Action Checklist
          </h3>
        </div>

        <button
          onClick={handleCopyChecklist}
          disabled={!recommendations || recommendations.length === 0}
          className="inline-flex items-center gap-1.5 px-3 py-1 text-xs font-mono rounded bg-slate-800 hover:bg-slate-750 text-slate-200 border border-slate-700 transition-colors"
        >
          {copied ? (
            <>
              <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
              <span>Checklist Copied!</span>
            </>
          ) : (
            <>
              <Copy className="w-3.5 h-3.5 text-slate-400" />
              <span>Copy Checklist</span>
            </>
          )}
        </button>
      </div>

      <div className="space-y-3">
        {recommendations.map((rec, index) => {
          const { border, badge, Icon, iconColor } = getPriorityStyle(rec.priority);
          return (
            <div
              key={index}
              className={`p-3.5 rounded-lg border ${border} transition-colors space-y-1.5`}
            >
              <div className="flex items-start justify-between gap-2">
                <div className="flex items-start gap-2">
                  <Icon className={`w-4 h-4 mt-0.5 shrink-0 ${iconColor}`} />
                  <span className="text-sm font-semibold text-slate-100">{rec.action}</span>
                </div>
                <span
                  className={`text-[10px] font-mono px-2 py-0.5 rounded border uppercase font-bold tracking-wider shrink-0 ${badge}`}
                >
                  {rec.priority}
                </span>
              </div>
              <p className="text-xs text-slate-300 pl-6 leading-relaxed">{rec.rationale}</p>
            </div>
          );
        })}
      </div>

      {isThreat && (
        <div className="p-3 bg-red-950/30 border border-red-900/50 rounded text-xs text-red-300/90 leading-relaxed font-sans">
          <strong>Security Advisory:</strong> Never forward suspicious messages or click embedded
          links to "test" them. ScamShield AI inspects links passively; manual opening in a browser
          may trigger drive-by scripts or tracking cookies.
        </div>
      )}
    </div>
  );
};
